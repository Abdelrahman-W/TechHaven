export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      return localStorage.getItem('th_lang') || 'ar';
    } catch {
      return 'ar';
    }
  });

  const isRtl = lang === 'ar';

  const setLang = (newLang) => {
    const safeLang = newLang === 'en' ? 'en' : 'ar';
    setLangState(safeLang);
    try {
      localStorage.setItem('th_lang', safeLang);
    } catch (e) {
      console.warn('Could not save language preference:', e);
    }
  };

  const toggleLang = () => {
    setLang(lang === 'ar' ? 'en' : 'ar');
  };

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
    if (isRtl) {
      document.body.classList.remove('th-ltr');
      document.body.classList.add('th-rtl');
    } else {
      document.body.classList.remove('th-rtl');
      document.body.classList.add('th-ltr');
    }
  }, [lang, isRtl]);

  const t = (key, fallback = '') => {
    return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS['ar']?.[key] ?? fallback ?? key;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, toggleLang, isRtl, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    // Fallback safe object if used outside provider
    return {
      lang: 'ar',
      isRtl: true,
      setLang: () => {},
      toggleLang: () => {},
      t: (key, fallback = '') => TRANSLATIONS.ar[key] || fallback || key,
    };
  }
  return context;
}
